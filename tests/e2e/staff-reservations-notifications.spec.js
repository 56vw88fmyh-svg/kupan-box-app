import { expect, test } from '@playwright/test'
import { openStaffApp } from './fixtures/staffApp.js'

test.use({ serviceWorkers: 'block' })

for (const viewport of [{ width: 320, height: 568 }, { width: 390, height: 844 }, { width: 844, height: 390 }, { width: 1280, height: 900 }]) {
  test(`notifications stay fully visible at ${viewport.width}x${viewport.height}`, async ({ page }) => {
    await page.setViewportSize(viewport)
    const state = await openStaffApp(page)
    const bell = page.getByRole('button', { name: 'Notificaciones KUPAN', exact: true })
    await bell.click()
    const dialog = page.getByRole('dialog', { name: 'Notificaciones', exact: true })
    await expect(dialog).toBeInViewport({ ratio: 1 })
    const box = await dialog.boundingBox()
    expect(box.x).toBeGreaterThanOrEqual(0)
    expect(box.x + box.width).toBeLessThanOrEqual(viewport.width)
    expect(box.y).toBeGreaterThanOrEqual(0)
    expect(box.y + box.height).toBeLessThanOrEqual(viewport.height)
    await expect(dialog.getByRole('heading', { name: 'Aviso 1', exact: true })).toBeVisible()
    await page.screenshot({ path: `test-results/notifications-${test.info().project.name}-${viewport.width}.png` })
    const last = dialog.getByRole('button', { name: /Aviso 20 / })
    await last.scrollIntoViewIfNeeded()
    await expect(last).toBeInViewport({ ratio: 1 })
    expect(state.notificationReads).toHaveLength(0)
    await page.screenshot({ path: `test-results/notifications-end-${test.info().project.name}-${viewport.width}.png` })
    await page.keyboard.press('Escape')
    await expect(dialog).toBeHidden()
    await expect(bell).toBeFocused()
    expect(await page.evaluate(() => document.body.style.position)).not.toBe('fixed')
    state.assertClean()
  })
}

test('Gestión adds an active Full student and keeps the form on a business rejection', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const state = await openStaffApp(page, { reservationError: 'El alumno ya tiene una reserva para esta clase.' })
  const menu = page.locator('#admin-quick-access')
  await menu.getByRole('button', { name: 'Clases', exact: true }).click()
  await menu.getByRole('button', { name: 'Agregar alumno a clase Reserva manual', exact: true }).click()
  const form = page.locator('form').filter({ has: page.getByRole('button', { name: 'Agregar a clase', exact: true }) })
  await form.getByRole('combobox', { name: 'Alumno', exact: true }).selectOption(state.student.id)
  await expect(form.getByText(/plan Full/)).toBeVisible()
  await form.getByRole('button', { name: 'Agregar a clase', exact: true }).click()
  await expect(form.getByRole('alert')).toContainText('ya está inscrito')
  await expect(form.getByRole('combobox', { name: 'Alumno', exact: true })).toHaveValue(state.student.id)
  state.reservationError = null
  await form.getByRole('button', { name: 'Agregar a clase', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Alumno agregado correctamente' })).toBeVisible()
  await expect(page.getByText(/Alumno con plan activo · Coach/)).toBeVisible()
  expect(state.requests).toHaveLength(2)
  expect(state.requests[1].allow_without_membership).toBe(false)
  state.assertClean()
})

test('Coach retries the options loader, shows the real booking reason and can submit again', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const state = await openStaffApp(page, { role: 'coach', path: '/coach', failOptionsOnce: true, reservationError: 'Clase completa.' })
  await page.getByRole('button', { name: 'Agregar alumno', exact: true }).click()
  await page.getByRole('button', { name: 'Volver a cargar alumnos', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Volver a cargar alumnos', exact: true })).toBeHidden()
  expect(state.optionRequests).toBeGreaterThan(1)
  await page.getByRole('combobox', { name: 'Alumno', exact: true }).selectOption(state.student.id)
  await page.getByRole('button', { name: 'Confirmar alumno', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('clase está completa')
  await expect(page.getByRole('combobox', { name: 'Alumno', exact: true })).toHaveValue(state.student.id)
  await expect(page.getByRole('button', { name: 'Reintentar', exact: true })).toBeHidden()
  state.reservationError = null
  await page.getByRole('button', { name: 'Confirmar alumno', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Acción realizada', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Alumno con plan activo', exact: true })).toBeVisible()
  expect(state.requests).toHaveLength(2)
  expect(state.requests[1].allow_without_membership).toBe(false)
  state.assertClean()
})
